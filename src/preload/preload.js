'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('aap', {
  init: () => ipcRenderer.invoke('app:init'),
  prepare: (input, opts, caps) => ipcRenderer.invoke('media:prepare', { input, opts, caps }),
  stopMedia: () => ipcRenderer.invoke('media:stop'),
  subtitle: (req) => ipcRenderer.invoke('media:subtitle', req),
  expand: (inputs) => ipcRenderer.invoke('media:expand', inputs),
  snapshot: (dataUrl, name, time) => ipcRenderer.invoke('media:snapshot', { dataUrl, name, time }),
  savePlaylist: (items) => ipcRenderer.invoke('playlist:save', items),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  toolsInfo: () => ipcRenderer.invoke('tools:info'),
  getLog: () => ipcRenderer.invoke('log:get'),
  log: (module, message) => ipcRenderer.send('log', { module, message }),
  addRecent: (input) => ipcRenderer.send('recent:add', input),
  setResume: (input, time, duration) => ipcRenderer.send('resume:set', { input, time, duration }),
  setMenuState: (state) => ipcRenderer.send('menu:state', state),
  setTitle: (title) => ipcRenderer.send('win:title', title),
  fullscreen: (value, withInterface) => ipcRenderer.invoke('win:fullscreen', value, withInterface),
  recordToggle: (req) => ipcRenderer.invoke('record:toggle', req),
  setWallpaper: (dataUrl) => ipcRenderer.invoke('wallpaper:set', dataUrl),
  menuAction: (name, arg) => ipcRenderer.send('menu:action', name, arg),
  convertProfiles: () => ipcRenderer.invoke('convert:profiles'),
  convertStart: (opts) => ipcRenderer.invoke('convert:start', opts),
  convertCancel: (id) => ipcRenderer.invoke('convert:cancel', id),
  convertList: () => ipcRenderer.invoke('convert:list'),
  convertClear: () => ipcRenderer.invoke('convert:clear'),
  savePath: (defaultName, ext) => ipcRenderer.invoke('dialog:save-path', { defaultName, ext }),
  discScan: () => ipcRenderer.invoke('disc:scan'),
  discTitles: (folder) => ipcRenderer.invoke('disc:titles', folder),
  pickFolder: () => ipcRenderer.invoke('dialog:pick-folder'),
  armCapture: () => ipcRenderer.send('capture:arm'),
  saveRecordingBlob: (data, ext) => ipcRenderer.invoke('record:save-blob', { data, ext }),
  quit: () => ipcRenderer.send('app:quit'),
  remoteGet: () => ipcRenderer.invoke('remote:get'),
  remoteSet: (patch) => ipcRenderer.invoke('remote:set', patch),
  remoteOpen: () => ipcRenderer.send('remote:open'),
  remoteStatus: (status) => ipcRenderer.send('remote:status', status),
  vlmGet: () => ipcRenderer.invoke('vlm:get'),
  vlmAdd: (req) => ipcRenderer.invoke('vlm:add', req),
  vlmRemove: (id) => ipcRenderer.invoke('vlm:remove', id),
  vlmNewPin: () => ipcRenderer.invoke('vlm:new-pin'),
  pickMedia: () => ipcRenderer.invoke('dialog:pick-media'),
  vlsubGet: () => ipcRenderer.invoke('vlsub:get'),
  vlsubConfig: (patch) => ipcRenderer.invoke('vlsub:config', patch),
  vlsubSuggest: (input) => ipcRenderer.invoke('vlsub:suggest', input),
  vlsubSearch: (query) => ipcRenderer.invoke('vlsub:search', query),
  vlsubDownload: (req) => ipcRenderer.invoke('vlsub:download', req),
  vlsubLogin: (username, password) => ipcRenderer.invoke('vlsub:login', { username, password }),
  vlsubLogout: () => ipcRenderer.invoke('vlsub:logout'),
  popupMenu: () => ipcRenderer.send('win:menu-popup'),
  resizeToVideo: (width, height) => ipcRenderer.send('win:resize-to-video', { width, height }),
  showInFolder: (file) => ipcRenderer.send('shell:show', file),
  pathForFile: (file) => webUtils.getPathForFile(file),
  onCommand: (fn) => ipcRenderer.on('cmd', (_e, name, arg) => fn(name, arg)),
});
